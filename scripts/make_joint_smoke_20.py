import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, "scripts", "joint_smoke.py"), encoding="utf-8").read().replace("\r\n", "\n")


def rep(a, b):
    global s
    assert s.count(a) == 1, f"anchor found {s.count(a)} times: {a!r}"
    s = s.replace(a, b)


